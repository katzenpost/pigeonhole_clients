"""Writes testdata/box_sizes.json: each named box size, measured by sealing a box with hpqc's
BACAP and framing its write as pigeonhole_rns and RNS do; katzenqt1 substreams cut to each; and
one stream whose boxes are of mixed sizes, as a group spanning meshes and mixnets writes. Needs
hpqc, RNS and pigeonhole_rns.

    python scripts/gen_box_sizes.py"""
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "py"))

import RNS  # noqa: E402
from hpqc.bacap.stateless import WriteCap  # noqa: E402
from pigeonhole_rns import PIGEONHOLE_CTX, channel  # noqa: E402
from pigeonhole_rns import wire as replica_wire  # noqa: E402
from pigeonhole_rns.client import pad  # noqa: E402
from RNS.vendor import umsgpack  # noqa: E402

from pigeonhole_protocols.katzenqt1 import wire  # noqa: E402
from pigeonhole_protocols.transport.base import BOX_SIZES, MAX_BOX_SIZE, MIN_BOX_SIZE, next_index, write_position  # noqa: E402
from pigeonhole_protocols.transport.reticulum import HEADROOM, mesh_box_size  # noqa: E402

OUT = os.path.join(HERE, "..", "testdata", "box_sizes.json")
EXTRA = 512


def data(n: int) -> bytes:
    return bytes(i % 251 for i in range(n))


def main():
    assert BOX_SIZES["mesh"] == mesh_box_size() and MIN_BOX_SIZE == wire.MIN_BOX
    wc = WriteCap.generate()
    sizes, substreams = [], []
    for name, size in BOX_SIZES.items():
        padded = pad(data(5), size)
        box_id, ciphertext, signature = wc.start().encrypt(PIGEONHOLE_CTX, padded)
        write = replica_wire.encode_write(box_id, signature, ciphertext)
        sizes.append({
            "name": name, "plaintext": size, "padded": len(padded), "ciphertext": len(ciphertext),
            "box_id": len(box_id), "signature": len(signature), "write_query": len(write),
            "channel_message": 6 + channel.HEADER.size + len(write),
            "link_request": len(umsgpack.packb([time.time(), RNS.Identity.truncated_hash(b"write"), write])),
            "pad": {"plaintext": data(5).hex(), "padded": padded.hex()},
        })
        for n in (size - 1, size, 2 * (size - 1) + 1):
            blob = data(n)
            boxes = [wire.substream_box(blob, size, i) for i in range(wire.chunk_count(n, size))]
            assert wire.assemble(boxes) == blob and all(len(b) <= size for b in boxes)
            substreams.append({"size": name, "message": blob.hex(), "boxes": [b.hex() for b in boxes]})

    # One substream, each box cut to the size its writer used then.
    rc = wc.read_cap().to_bytes()
    index, boxes, plaintexts = rc[32:], [], []
    cuts = [(BOX_SIZES["mesh"], wire.CONTINUED, BOX_SIZES["mesh"] - 1), (BOX_SIZES["mixnet"], wire.CONTINUED, BOX_SIZES["mixnet"] - 1),
            (EXTRA, wire.CONTINUED, EXTRA - 1), (BOX_SIZES["mesh"], wire.FINAL, 100)]
    for n, (size, tag, length) in enumerate(cuts):
        plaintext = tag + bytes((n + i) % 251 for i in range(length))
        box_id, ciphertext, signature = write_position(wc.to_bytes(), index).encrypt(PIGEONHOLE_CTX, pad(plaintext, size))
        boxes.append({"size": size, "index": index.hex(), "box_id": box_id.hex(), "signature": signature.hex(), "ciphertext": ciphertext.hex()})
        plaintexts.append(plaintext)
        index = next_index(index)
    out = {
        "about": "Box sizes, in bytes. plaintext is the most a box of that size holds; padded is the "
        "plaintext after Katzenpost's padding (a big endian u32 length, the plaintext, zeros); ciphertext "
        "is the padded plaintext sealed by BACAP; write_query is a mesh replica's write query (type byte, "
        "box ID, signature, ciphertext); channel_message is it as one Channel message (6 byte envelope, 4 "
        "byte frame header) and link_request as a Link request (msgpack of [time, path hash, query]). "
        "mesh, a writer's default on Reticulum, is the largest multiple of 16 whose channel_message and "
        "link_request leave headroom bytes of one Link packet (link_mdu) spare; mixnet is Katzenpost's. "
        "Only the payload differs: box IDs and signatures are the same size in each. A reader takes a box "
        "of any allowed size: the named ones, its writer's own and configured extras, each within "
        "min..max. mixed_stream is one stream, read with read_cap from its first index on, whose boxes "
        "are of different sizes, extra_sizes among them: they hold one substream, whose message is "
        "assembled. Generated by scripts/gen_box_sizes.py.",
        "min": MIN_BOX_SIZE,
        "max": MAX_BOX_SIZE,
        "link_mdu": RNS.Link.MDU,
        "headroom": HEADROOM,
        "sizes": sizes,
        "substreams": substreams,
        "mixed_stream": {
            "read_cap": rc.hex(),
            "extra_sizes": [EXTRA],
            "boxes": boxes,
            "plaintexts": [p.hex() for p in plaintexts],
            "message": wire.assemble(plaintexts).hex(),
        },
    }
    with open(OUT, "w") as f:
        json.dump(out, f, indent=1)
        f.write("\n")


if __name__ == "__main__":
    main()
