"""Writes testdata/katzenqt1/groupchat_wire_vectors_v5.json: what version 5 of the katzenqt1
wire adds, msg_type 12, several text messages packed in one box, so that each language's codec
is checked against the same bytes.

    python scripts/gen_groupchat_wire_vectors_v5.py

packed: a text message (start), the texts packed into it one by one (added), the packed CBOR
that makes, the texts it reads as and what a member reads of it. unsupported: messages a reader
of version 5 refuses and names the version and type of, as the engine tells the user. malformed:
what it refuses and names nothing of."""
import json
import os
import sys

import cbor2

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "py"))
sys.path.insert(0, os.path.join(HERE, "..", "py", "tests"))

from pigeonhole_protocols.katzenqt1 import wire  # noqa: E402
from pigeonhole_protocols.katzenqt1.member import ack_codec  # noqa: E402
from test_wire_vectors import message_json  # noqa: E402

TESTDATA = os.path.join(HERE, "..", "testdata", "katzenqt1")
H = bytes(range(32))


def main():
    out = {"about": "Version 5 of the katzenqt1 wire is version 4 and msg_type 12, several text messages in one box: the GroupChatMessage array [5, membership_hash, 12, [text, ...], acks, numbers, introduced_at] with trailing nulls left out. A sender packs a text message into the one before it while that waits to be written; acks are those the first message was composed with. A reader of version 4 refuses msg_type 12 as a type it does not know, and a reader of version 5 any version above 5 or type it does not know; either names the version and type, and the engine tells the user who sent it. Generated by scripts/gen_groupchat_wire_vectors_v5.py."}
    acks = ack_codec.encode({0: 7, 3: 300})
    starts = [
        ("two", wire.text_content(H, "one"), ["two"]),
        ("three-unicode", wire.text_content(H, "grüße"), ["日本語", "🙂"]),
        ("empty-texts", wire.text_content(H, ""), [""]),
        ("from-version-4", wire.text_content(H, "old", wire.ARRAY_VERSION), ["new"]),
        ("with-acks", wire.Gcm(wire.VERSION, H, wire.MSG_TEXT, text="hello", acks=acks).encode(), ["again", "and again"]),
    ]
    packed = []
    for name, start, added in starts:
        cbor = start
        for t in added:
            cbor = wire.pack(cbor, t)
        g = wire.decode_gcm(cbor)
        texts = [wire.decode_gcm(start).text] + added
        assert g.version == wire.PACKED_VERSION and g.msg_type == wire.MSG_PACKED and g.texts == texts and g.encode() == cbor, name
        assert wire.texts_of(cbor) == texts, name
        m = wire.to_message(cbor)
        packed.append({"name": name, "start": start.hex(), "added": added, "cbor": cbor.hex(), "texts": texts, "message": {**message_json(m), "membership_hash": None}})
    unsupported = [
        {"name": "version-6-text", "cbor": cbor2.dumps([6, H, 0, "hi"]).hex(), "version": 6, "msg_type": 0},
        {"name": "version-6-packed", "cbor": cbor2.dumps([6, H, 12, ["a", "b"]]).hex(), "version": 6, "msg_type": 12},
        {"name": "version-300", "cbor": cbor2.dumps([300, H, 10, None]).hex(), "version": 300, "msg_type": 10},
        {"name": "packed-in-version-4", "cbor": cbor2.dumps([4, H, 12, ["a"]]).hex(), "version": 4, "msg_type": 12},
        {"name": "type-13", "cbor": cbor2.dumps([5, H, 13, ["a"]]).hex(), "version": 5, "msg_type": 13},
    ]
    for e in unsupported:
        assert wire.decode_gcm(bytes.fromhex(e["cbor"])) is None and wire.unsupported(bytes.fromhex(e["cbor"])) == (e["version"], e["msg_type"]), e["name"]
    malformed = [
        {"name": "texts-not-array", "cbor": cbor2.dumps([5, H, 12, "hi"]).hex()},
        {"name": "no-texts", "cbor": cbor2.dumps([5, H, 12, []]).hex()},
        {"name": "not-all-texts", "cbor": cbor2.dumps([5, H, 12, ["a", 7]]).hex()},
        {"name": "ping-with-texts", "cbor": cbor2.dumps([5, H, 11, ["a"]]).hex()},
        {"name": "text-as-array", "cbor": cbor2.dumps([5, H, 0, ["a"]]).hex()},
        {"name": "short-hash", "cbor": cbor2.dumps([5, bytes(31), 12, ["a"]]).hex()},
    ]
    for e in malformed:
        assert wire.decode_gcm(bytes.fromhex(e["cbor"])) is None and wire.unsupported(bytes.fromhex(e["cbor"])) is None, e["name"]
    out.update(packed=packed, unsupported=unsupported, malformed=malformed)
    with open(os.path.join(TESTDATA, "groupchat_wire_vectors_v5.json"), "w") as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(len(packed), "packed", len(unsupported), "unsupported", len(malformed), "malformed")


if __name__ == "__main__":
    main()
